function showFace(stack, name) {
  if (faces.get(stack)?.name === name) return;
  const images = [...stack.querySelectorAll("img:not(.blink-face)")];
  const active = images.find(image => image.classList.contains("is-face")) || images[0];
  const next = images.find(image => image !== active);
  const request = { name };
  faces.set(stack, request);
  const src = facePath(name);
  if (active.getAttribute("src") === src) return;
  next.src = src;
  const reveal = () => {
    if (faces.get(stack) !== request) return;
    stack.classList.add("initialized");
    active.classList.remove("is-face");
    next.classList.add("is-face");
  };
  if (next.complete && next.naturalWidth) reveal();
  else next.decode().then(reveal).catch(() => {
    if (faces.get(stack) === request) faces.delete(stack);
  });
}

